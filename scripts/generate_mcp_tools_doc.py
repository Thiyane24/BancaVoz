from __future__ import annotations

from pathlib import Path

from fastapi.testclient import TestClient

from bancavoz.api import app

EXAMPLES = {
    "log_sale": ("Logged. MZN 1,350.00 total. Maria owes MZN 675.00.",
                 "unit_price is required"),
    "log_expense": ("Logged expense. MZN 200.00 transport.", "amount is required"),
    "record_credit_payment": ("Logged. Maria paid MZN 300.00.", "payment exceeds balance for Maria"),
    "get_credit_owed": ("Maria owes MZN 675.00.", "customer not found"),
    "get_daily_summary": ("Today: MZN 1,350.00 sales, MZN 200.00 expenses.",
                          "unknown timezone: Mars/Olympus"),
    "undo_last_entry": ("Last entry undone.", "no live entries to undo"),
    "get_top_sellers": ("Top seller: rice, MZN 1,350.00 revenue.", "period must be today, week, or month"),
    "set_stock": ("Stock updated. rice: 20.", "stock values must be non-negative"),
    "check_low_stock": ("2 items are running low.", "database not ready"),
    "get_daily_digest": ("Today: MZN 1,350.00 sales, MZN 200.00 expenses.",
                         "digest facts are invalid"),
}


def main() -> None:
    headers = {"Authorization": "Bearer dev-token", "Accept": "application/json, text/event-stream"}
    with TestClient(app) as client:
        initialized = client.post(
            "/mcp/",
            headers=headers,
            json={"jsonrpc": "2.0", "id": 1, "method": "initialize",
                  "params": {"protocolVersion": "2025-03-26", "capabilities": {},
                             "clientInfo": {"name": "docgen", "version": "1"}}},
        )
        initialized.raise_for_status()
        response = client.post(
            "/mcp/",
            headers=headers,
            json={"jsonrpc": "2.0", "id": 2, "method": "tools/list", "params": {}},
        )
        response.raise_for_status()
    tools = response.json()["result"]["tools"]
    lines = [
        "# MCP tools",
        "",
        "Generated by `python scripts/generate_mcp_tools_doc.py` from the official",
        "Streamable HTTP `tools/list` response. The captured protocol smoke run",
        "returned HTTP 200 for `initialize` and `tools/list` and 10 tools.",
        "",
    ]
    for tool in tools:
        schema = tool["inputSchema"]
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines += [f"## `{tool['name']}`", "", tool["description"], "", "| Argument | Required | Default / type |", "| --- | --- | --- |"]
        for name, spec in properties.items():
            types = spec.get("type") or " | ".join(x.get("type", "?") for x in spec.get("anyOf", []))
            default = spec.get("default", "—")
            lines.append(f"| `{name}` | {'yes' if name in required else 'no'} | `{types}`, default `{default}` |")
        speech, error = EXAMPLES.get(tool["name"], ("Success.", "Invalid request."))
        lines += ["", f"**Example speech:** {speech}", f"**Example error speech:** {error}", ""]
    Path("docs/MCP_TOOLS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"generated docs/MCP_TOOLS.md from {len(tools)} tools")


if __name__ == "__main__":
    main()
